PRAGMA foreign_keys = ON;
BEGIN IMMEDIATE;
CREATE TABLE IF NOT EXISTS users (
  id INTEGER PRIMARY KEY,
  username TEXT NOT NULL UNIQUE COLLATE NOCASE,
  password TEXT NOT NULL,
  id_badges INTEGER NOT NULL DEFAULT 0
);
CREATE TABLE IF NOT EXISTS badges (
  id INTEGER PRIMARY KEY,
  id_account INTEGER NOT NULL UNIQUE REFERENCES users(id),
  "1poging" INTEGER NOT NULL DEFAULT 0,
  "10pogingen" INTEGER NOT NULL DEFAULT 0,
  coach INTEGER NOT NULL DEFAULT 0,
  geeflike INTEGER NOT NULL DEFAULT 0,
  nummer1 INTEGER NOT NULL DEFAULT 0,
  populair INTEGER NOT NULL DEFAULT 0,
  ranglijst INTEGER NOT NULL DEFAULT 0,
  tijd INTEGER NOT NULL DEFAULT 0,
  tip INTEGER NOT NULL DEFAULT 0,
  uitdager INTEGER NOT NULL DEFAULT 0
);
CREATE TABLE IF NOT EXISTS videos (
  id INTEGER PRIMARY KEY,
  time INTEGER NOT NULL CHECK (time > 0),
  id_account INTEGER NOT NULL REFERENCES users(id),
  path TEXT NOT NULL UNIQUE,
  path_thumbnail INTEGER NOT NULL DEFAULT 0
);
CREATE TABLE IF NOT EXISTS comments (
  id INTEGER PRIMARY KEY,
  comment TEXT NOT NULL,
  id_video INTEGER NOT NULL REFERENCES videos(id),
  id_account INTEGER NOT NULL REFERENCES users(id),
  username TEXT NOT NULL
);
CREATE TABLE IF NOT EXISTS video_reactions (
  id INTEGER PRIMARY KEY,
  id_video INTEGER NOT NULL REFERENCES videos(id),
  id_account INTEGER NOT NULL REFERENCES users(id)
);
CREATE INDEX IF NOT EXISTS comments_video ON comments(id_video);
CREATE INDEX IF NOT EXISTS comments_account ON comments(id_account);
CREATE INDEX IF NOT EXISTS reactions_video ON video_reactions(id_video);
